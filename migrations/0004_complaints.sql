CREATE TABLE company_suggestions (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  user_id BIGINT UNSIGNED NOT NULL,
  name VARCHAR(120) NOT NULL,
  country_code CHAR(2) NOT NULL,
  city_id INT UNSIGNED NOT NULL,
  category_id INT UNSIGNED NOT NULL,
  website VARCHAR(200) NULL,
  registry_no VARCHAR(30) NULL,
  status ENUM('pending','approved','merged','rejected') NOT NULL DEFAULT 'pending',
  merged_into_company_id BIGINT UNSIGNED NULL,
  created_at DATETIME NOT NULL DEFAULT (UTC_TIMESTAMP()),
  KEY ix_sugg_status (status, created_at),
  KEY ix_sugg_user (user_id),
  CONSTRAINT fk_sugg_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
  CONSTRAINT fk_sugg_city FOREIGN KEY (city_id) REFERENCES cities(id),
  CONSTRAINT fk_sugg_cat FOREIGN KEY (category_id) REFERENCES categories(id),
  CONSTRAINT fk_sugg_company FOREIGN KEY (merged_into_company_id) REFERENCES companies(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE complaints (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  user_id BIGINT UNSIGNED NOT NULL,
  company_id BIGINT UNSIGNED NULL,
  suggestion_id BIGINT UNSIGNED NULL,
  title VARCHAR(140) NOT NULL,
  body TEXT NOT NULL,
  incident_date DATE NOT NULL,
  amount DECIMAL(12,2) NULL,
  currency CHAR(3) NULL,
  status ENUM('awaiting_company','pending','published','rejected','removed','resolved') NOT NULL DEFAULT 'pending',
  reject_reason VARCHAR(300) NULL,
  risk_score SMALLINT NULL,
  risk_flags JSON NULL,
  ip_hmac CHAR(64) NULL,
  created_at DATETIME NOT NULL DEFAULT (UTC_TIMESTAMP()),
  published_at DATETIME NULL,
  resolved_at DATETIME NULL,
  KEY ix_comp_company (company_id, status, published_at),
  KEY ix_comp_user (user_id, created_at),
  KEY ix_comp_status (status, created_at),
  KEY ix_comp_pub (status, published_at),
  CONSTRAINT fk_comp_user FOREIGN KEY (user_id) REFERENCES users(id),
  CONSTRAINT fk_comp_company FOREIGN KEY (company_id) REFERENCES companies(id),
  CONSTRAINT fk_comp_sugg FOREIGN KEY (suggestion_id) REFERENCES company_suggestions(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
